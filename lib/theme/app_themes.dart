  static ThemeData themeFor(AppThemeId id) {
    final colors = _colorsFor(id);
    final brightness = id.isDark ? Brightness.dark : Brightness.light;
    final textTheme = AppTextStyles.textTheme(colors);

    return ThemeData(
      brightness: brightness,
      colorScheme: ColorScheme.fromSeed(
        seedColor: colors.aiAccent,
        error: colors.error,
        brightness: brightness,
        surface: colors.surface,
        onSurface: colors.onScaffold,
      ),
      scaffoldBackgroundColor: colors.scaffoldBackground,
      textTheme: textTheme,
      iconTheme: IconThemeData(color: colors.onScaffold),
      listTileTheme: ListTileThemeData(
        iconColor: colors.onScaffold,
        textColor: colors.onScaffold,
      ),
      textButtonTheme: TextButtonThemeData(
        style: TextButton.styleFrom(foregroundColor: colors.onScaffold),
      ),
      inputDecorationTheme: InputDecorationTheme(
        filled: true,
        fillColor: colors.surfaceSecondary,
        labelStyle: textTheme.bodyMedium,
        hintStyle: textTheme.bodySmall,
        border: OutlineInputBorder(
          borderRadius: BorderRadius.circular(12),
          borderSide: BorderSide(color: colors.border),
        ),
        enabledBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(12),
          borderSide: BorderSide(color: colors.border),
        ),
        focusedBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(12),
          borderSide: BorderSide(color: colors.primaryAction, width: 1.5),
        ),
      ),
      dialogTheme: DialogThemeData(
        backgroundColor: colors.surface,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
      ),
      bottomSheetTheme: BottomSheetThemeData(
        backgroundColor: colors.surface,
        shape: const RoundedRectangleBorder(
          borderRadius: BorderRadius.vertical(top: Radius.circular(16)),
        ),
      ),
      extensions: [colors],
    );
  }

